// Builds test/web_parity_data.dart: a small bank, RNG sequences and two
// puzzles, embedded in a Dart string so the test can run in a browser.
import { readFileSync } from 'node:fs';
import { generate } from '../src/generator.ts';
import { toFullJson } from '../src/puzzle_json.ts';
import { Rng } from '../src/rng.ts';

export const WEB_PARITY_PATH = new URL('../../test/web_parity_data.dart', import.meta.url);

export function buildWebParityDart(): string {
  const bank = JSON.parse(
    readFileSync(new URL('../../words/bank_v1.json', import.meta.url), 'utf8'),
  ).filter((e: { id: number }) => e.id % 9 === 1).slice(0, 60);
  const rng = ['', 'a', 'لغز-١', 'daily-2026-11-15#0'].map((seed) => {
    const r = new Rng(seed);
    return { seed, values: Array.from({ length: 8 }, () => r.next()) };
  });
  const cases = ([[7, 'web'], [9, 'daily-2026-11-15']] as [number, string][]).map(
    ([size, seed]) => ({
      size,
      seed,
      json: toFullJson(generate(bank, { size, seed }), `practice-${size}-${seed}`),
    }),
  );
  return `// GENERATED by core-ts/scripts/web-parity.ts (npm run fixtures). Do not edit.
// A small bank, RNG sequences and two puzzles, embedded as a string so the
// test can also run in a browser (no dart:io).
const String webParityJson = r'''
${JSON.stringify({ bank, rng, cases })}
''';
`;
}
